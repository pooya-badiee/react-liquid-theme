import { PassThrough } from 'node:stream'
import liquidPlugin from '@shopify/prettier-plugin-liquid/standalone.js'
import * as prettier from 'prettier'
import type { ReactNode } from 'react'
import { renderToPipeableStream } from 'react-dom/server'
import { DECODE_END_SIGN, DECODE_START_SIGN } from '../liquid-react/components/html-decoder/constants'
import { decodeHtml } from '../liquid-react/components/html-decoder/decode-html'

/** `sourceFile` is shown so readers of the theme know which file to edit */
export function getHeaderComment(sourceFile?: string) {
  const editLine = sourceFile ? `Edit the source file instead:\n  ${sourceFile}` : 'Modify source files instead.'
  return `
{%- comment -%}
  ------------------------------------------------------------------
  ⚠️  AUTO-GENERATED — DO NOT EDIT
  ------------------------------------------------------------------

  Generated by react-liquid-theme. Changes will be overwritten.
  ${editLine}

  ------------------------------------------------------------------
{%- endcomment -%}
`
}

export type HtmlWhitespaceSensitivity = 'css' | 'strict' | 'ignore'

export interface RenderOptions {
  leaveComment?: boolean
  /** Source file named in the header comment, relative to the project root */
  sourceFile?: string | undefined
  /**
   * Passed to prettier. `css` (default) keeps rendered whitespace as is, e.g. `<a>Terms</a>.` stays glued.
   * `ignore` formats more freely but can add visible spaces between inline elements and text.
   */
  htmlWhitespaceSensitivity?: HtmlWhitespaceSensitivity | undefined
}

export async function renderToString(
  reactNode: ReactNode,
  { leaveComment = false, sourceFile, htmlWhitespaceSensitivity = 'css' }: RenderOptions = {},
): Promise<string> {
  return await new Promise<string>((resolve, reject) => {
    const stream = new PassThrough()
    let html = ''

    stream.setEncoding('utf8')
    stream.on('data', (chunk: string) => {
      // removes dead html comments
      html += removeTrashComments(chunk)
    })
    stream.on('end', async () => {
      html = decodeHtml(html, DECODE_START_SIGN, DECODE_END_SIGN)
      html = await prettier.format((leaveComment ? getHeaderComment(sourceFile) : '') + html, {
        parser: 'liquid-html',
        plugins: [liquidPlugin],
        printWidth: 120,
        tabWidth: 2,
        singleQuote: true,
        trailingComma: 'all',
        htmlWhitespaceSensitivity,
      })
      resolve(html)
    })
    stream.on('error', reject)

    const { pipe } = renderToPipeableStream(reactNode, {
      onAllReady() {
        pipe(stream)
      },
      onError(error) {
        console.error('Render error:', error)
      },
    })
  })
}

export function removeTrashComments(html: string): string {
  return html.replace(/<!--\s*-->|\\x3C!--\s*-->/g, '')
}
